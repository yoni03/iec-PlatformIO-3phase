"""Compresses web/index.html into src/web_ui.h (a gzip byte array in flash).

Runs automatically before every PlatformIO build (extra_scripts), and can be
run by hand:  python3 tools/embed_web.py
"""
import gzip
import os
import re

try:
    Import("env")  # noqa: F821  (PlatformIO / SCons)
    ROOT = env.subst("$PROJECT_DIR")  # noqa: F821
except NameError:
    ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

SRC = os.path.join(ROOT, "web", "index.html")
DST = os.path.join(ROOT, "src", "web_ui.h")


def embedded(text):
    """The page stored in an existing web_ui.h, or None."""
    try:
        body = text.split("PROGMEM = {", 1)[1]
        return gzip.decompress(bytes(int(x, 16) for x in re.findall(r"0x([0-9a-f]{2})", body)))
    except Exception:
        return None


def build():
    with open(SRC, "rb") as f:
        raw = f.read()
    data = gzip.compress(raw, compresslevel=9, mtime=0)
    lines = []
    for i in range(0, len(data), 20):
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 20]) + ",")
    out = (
        "// Generated by tools/embed_web.py from web/index.html. Do not edit.\n"
        "#pragma once\n#include <Arduino.h>\n\n"
        f"// {len(raw)} bytes -> {len(data)} bytes gzip\n"
        f"const size_t INDEX_HTML_GZ_LEN = {len(data)};\n"
        "const uint8_t INDEX_HTML_GZ[] PROGMEM = {\n" + "\n".join(lines) + "\n};\n"
    )
    old = open(DST).read() if os.path.exists(DST) else ""
    # gzip output differs between zlib versions: rewrite the header only when
    # the page itself changed, so builds do not leave a modified file behind
    if old and embedded(old) == raw:
        return
    if out != old:
        with open(DST, "w") as f:
            f.write(out)
        print(f"embed_web: {len(raw)} -> {len(data)} bytes gzip")


build()
